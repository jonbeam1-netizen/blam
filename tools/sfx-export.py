#!/usr/bin/env python
"""Export the locked picks from review/sfx-picks (gitignored) into assets/sfx (tracked, shipped) and write
assets/sfx/manifest.json, the one file the game reads to know which samples belong to which sound event.
  python tools/sfx-export.py
Every file is copied as-is (mono 16-bit 44.1 k WAV, already balanced by tools/sfx-balance.py: shots -10 dBFS punch,
reloads -13, hit breaks -10, hit dings -22, ricochets -14, bombs -8, duck -16). Re-run after any pick changes."""
import json, pathlib, shutil, glob, subprocess
ROOT = pathlib.Path(__file__).resolve().parent.parent
P, A = ROOT / 'review' / 'sfx-picks', ROOT / 'assets' / 'sfx'
A.mkdir(parents=True, exist_ok=True)

def files(pattern):
    out = sorted(P.glob(pattern), key=lambda f: (len(f.stem), f.stem))
    return [f for f in out if f.suffix == '.wav']

# event set -> glob in review/sfx-picks. Names on the left are what js/core/sfx-samples.js looks up.
SETS = {
    'shot.hotrod': 'gun-hotrod-rr-*.wav', 'shot.aquapro': 'gun-aquapro-rr-*.wav',
    'shot.ray85': 'gun-ray85-rr-*.wav', 'shot.candysix': 'gun-candysix-rr-*.wav',
    'reload.hotrod': 'gun-hotrod-reload-*.wav', 'reload.aquapro': 'gun-aquapro-reload-*.wav',
    'reload.ray85': 'gun-ray85-reload-*.wav', 'reload.candysix': 'gun-candysix-reload-*.wav',
    'hitBreak': 'target-break-*.wav', 'hitDing': 'target-ding-*.wav',
    'ricochet': 'ricochet-*.wav', 'bomb': 'bomb-*.wav',
    'duckAngry': 'duck-angry-?.wav', 'duckHeckle': 'duck-heckle-*.wav', 'duckHappy': 'duck-happy-*.wav',
    'duckHit': 'duck-hit-*.wav', 'duckScared': 'duck-scared-*.wav', 'duckRelief': 'duck-relief-*.wav',
    'duckCheer': 'duck-cheer-*.wav', 'duckSad': 'duck-sad-*.wav',
}
def dur(f):
    try: return round(float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(f)], capture_output=True, text=True).stdout.strip()), 3)
    except Exception: return None

manifest = {
    'version': 1,
    'note': 'Generated by tools/sfx-export.py from review/sfx-picks. Levels are pre-balanced (see tools/sfx-balance.py); '
            'the game should play these at unity gain relative to each other and only apply the master volume.',
    'rules': {
        'roundRobin': 'shuffle bag per set, never the same file twice in a row, pitch jitter +-3 % on shots/hits, +-5 % on duck',
        'shot': 'one file from shot.<gunSkin>; a shot cuts any reload sample still playing (and snaps the rack animation)',
        'reload': 'reload.<gunSkin>, one file, 0.40 s; a shot interrupts it',
        'hit': 'one hitBreak + one hitDing 12 ms later; the ding pitch steps up +1 semitone per consecutive hit (cap +7), resets on a miss',
        'ricochet': 'play on a miss (shot hit nothing) and on the title marquee; random stereo pan in [-0.8, 0.8] every time',
        'bomb': 'one file, also duck the sfx bus ~4 dB for 0.3 s',
        'duck': 'duck* sets replace the synthesized duck voice; same pose mapping as audio.js DUCK_POSES',
    },
    'sets': {},
}
kept = set()
for name, pat in SETS.items():
    fs = files(pat)
    if not fs: print(f'  (none for {name}: {pat})'); continue
    entry = []
    for f in fs:
        shutil.copy(f, A / f.name); kept.add(f.name)
        entry.append({'file': f.name, 'dur': dur(f)})
    manifest['sets'][name] = entry
    print(f'{name:16s} {len(fs)} files')
# drop stale copies
for f in A.glob('*.wav'):
    if f.name not in kept: f.unlink(); print('  removed stale', f.name)
(A / 'manifest.json').write_text(json.dumps(manifest, indent=1), encoding='utf-8')
total = sum(f.stat().st_size for f in A.glob('*.wav'))
print(f'wrote {A / "manifest.json"}  ({len(kept)} wavs, {total / 1e6:.1f} MB)')
